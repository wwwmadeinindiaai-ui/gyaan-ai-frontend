/**
 * Manages user data source connections in Firestore.
 */
class DataSourceManager {
  private readonly COLLECTION_NAME = 'dataSources';

  async addSource(sourceData, userId) {
    const { db } = await getAuthenticatedFirestore();
    const sourcesRef = getUserCollectionRef(db, userId, this.COLLECTION_NAME);
    
    const now = new Date();
    const newSource = {
      ...sourceData,
      userId: userId,
      isActive: true,
      testStatus: 'pending',
      createdAt: Timestamp.fromDate(now),
      lastTested: Timestamp.fromDate(now),
    };

    try {
      const docRef = await addDoc(sourcesRef, newSource);
      return docRef.id;
    } catch (error) {
      console.error("Error adding data source:", error);
      throw new Error("Failed to add data source to database.");
    }
  }

  validateSource(source) {
    if (!source.name || source.name.trim().length < 3) return false;
    if (!['api', 'database', 'file', 'web'].includes(source.type)) return false;
    
    if ((source.type === 'api' || source.type === 'web') && (!source.config || !source.config.endpoint)) {
        return false;
    }

    return true;
  }

  async testConnection(sourceId, userId) {
    await new Promise(resolve => setTimeout(resolve, 800));

    const testSuccessful = Math.random() > 0.1;

    const { db } = await getAuthenticatedFirestore();
    const sourceDocRef = doc(getUserCollectionRef(db, userId, this.COLLECTION_NAME), sourceId);

    const update = {
      lastTested: Timestamp.fromDate(new Date()),
      testStatus: testSuccessful ? 'success' : 'failed',
    };

    try {
        await updateDoc(sourceDocRef, update);
        return testSuccessful;
    } catch (error) {
        console.error(`Error updating test status for source ${sourceId}:`, error);
        return false;
    }
  }

  async updateSource(sourceId, userId, updates) {
    const { db } = await getAuthenticatedFirestore();
    const sourceDocRef = getUserDocumentRef(db, userId, this.COLLECTION_NAME, sourceId);
    
    const updatePayload = {};

    for (const key in updates) {
        if (updates.hasOwnProperty(key)) {
            const value = updates[key];
            if (value instanceof Date) {
                updatePayload[key] = Timestamp.fromDate(value);
            } else {
                updatePayload[key] = value;
            }
        }
    }
    
    try {
      await updateDoc(sourceDocRef, updatePayload);
    } catch (error) {
      console.error(`Error updating source ${sourceId}:`, error);
      throw new Error(`Failed to update data source ${sourceId}.`);
    }
  }

  async removeSource(sourceId, userId) {
    const { db } = await getAuthenticatedFirestore();
    const sourceDocRef = doc(getUserCollectionRef(db, userId, this.COLLECTION_NAME), sourceId);
    
    try {
      await deleteDoc(sourceDocRef);
    } catch (error) {
      console.error(`Error deleting source ${sourceId}:`, error);
      throw new Error(`Failed to delete data source ${sourceId}.`);
    }
  }

  getSourcesSnapshot(userId, callback, onError) {
    const dbPromise = getAuthenticatedFirestore();
    let unsubscribe = () => {};

    dbPromise.then(({ db }) => {
        const sourcesRef = getUserCollectionRef(db, userId, this.COLLECTION_NAME);
        
        unsubscribe = onSnapshot(sourcesRef, (snapshot) => {
            const sources = snapshot.docs.map(d => {
                const data = d.data();
                return {
                    id: d.id,
                    userId: userId,
                    name: data.name,
                    type: data.type,
                    config: data.config || {},
                    isPrivate: data.isPrivate || false,
                    isActive: data.isActive === undefined ? true : data.isActive,
                    lastTested: data.lastTested?.toDate() || new Date(0), 
                    testStatus: data.testStatus || 'pending',
                    createdAt: data.createdAt?.toDate() || new Date(0),
                };
            });
            callback(sources);
        }, (error) => {
            console.error("Firestore snapshot error:", error);
            onError(error);
        });
    }).catch(onError);

    return () => unsubscribe();
  }
}

