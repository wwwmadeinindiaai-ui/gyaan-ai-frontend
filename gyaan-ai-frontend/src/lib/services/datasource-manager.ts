// Global variables provided by the canvas environment
declare const __firebase_config: string | undefined;
declare const __app_id: string | undefined;
declare const __initial_auth_token: string | undefined;

let app = null;
let db = null;
let auth = null;
let currentUserId = null;
const appId = typeof __app_id !== 'undefined' ? __app_id : 'default-app-id';

async function initializeAndAuthenticate() {
    if (app) return; 

    try {
        const firebaseConfig = typeof __firebase_config !== 'undefined' 
            ? JSON.parse(__firebase_config) 
            : {};

        app = initializeApp(firebaseConfig);
        db = getFirestore(app);
        auth = getAuth(app);
        
        if (typeof __initial_auth_token !== 'undefined' && __initial_auth_token) {
            await signInWithCustomToken(auth, __initial_auth_token);
        } else {
            await signInAnonymously(auth);
        }

        onAuthStateChanged(auth, (user) => {
            currentUserId = user ? user.uid : null;
        });
        
    } catch (e) {
        console.error("Firebase initialization or authentication failed:", e);
    }
}

async function getAuthenticatedFirestore() {
    await initializeAndAuthenticate();
    
    if (!db || !auth || !currentUserId) {
        await new Promise(resolve => setTimeout(resolve, 100));
    }
    
    if (!db || !auth) throw new Error("Firebase services are not ready.");
    
    const userId = currentUserId || auth.currentUser?.uid || crypto.randomUUID();
    
    return { db, auth, userId };
}

function getUserCollectionRef(dbInstance, userId, collectionName) {
    const path = `artifacts/${appId}/users/${userId}/${collectionName}`;
    return collection(dbInstance, path);
}

function getUserDocumentRef(dbInstance, userId, collectionName, docId) {
    return doc(getUserCollectionRef(dbInstance, userId, collectionName), docId);
}

